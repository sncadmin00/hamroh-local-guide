type GuideTextKey = keyof typeof guideTranslations;

export function guideDateLocale(lang: Lang) {
  if (lang === "ru") return "ru-RU";
  if (lang === "uz") return "uz-UZ";
  return "en-US";
}

export function guideSpeechLocale(lang: Lang) {
  if (lang === "ru") return "ru-RU";
  if (lang === "uz") return "uz-UZ";
  return "en-US";
}

export function useGuideI18n() {
  const { lang } = useI18n();
  const tg = (key: GuideTextKey, vars?: Record<string, string | number>) => {
    let value: string = guideTranslations[key]?.[lang] ?? guideTranslations[key]?.en ?? String(key);
    if (vars) {
      for (const [name, replacement] of Object.entries(vars)) {
        value = value.replaceAll(`{${name}}`, String(replacement));
      }
    }
    return value;
  };
  return { lang, tg };
}