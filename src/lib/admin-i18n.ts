type AdminTextKey = keyof typeof adminTranslations;

export function useAdminI18n() {
  const { lang } = useI18n();
  const ta = (key: AdminTextKey, vars?: Record<string, string | number>) => {
    let value: string = adminTranslations[key]?.[lang] ?? adminTranslations[key]?.en ?? String(key);
    if (vars) {
      for (const [name, replacement] of Object.entries(vars)) {
        value = value.replaceAll(`{${name}}`, String(replacement));
      }
    }
    return value;
  };
  return { lang, ta };
}
